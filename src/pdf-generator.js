const PDFDocument = require('pdfkit');
const fs = require('fs');
const path = require('path');
const config = require('./config');
const logger = require('./logger');

// Strip non-Latin1 characters that crash PDFKit's default Helvetica font
function sanitizeText(text) {
  if (!text) return '';
  return String(text).replace(/[^\x00-\xFF]/g, '?');
}

async function generateReport(emails, options = {}) {
  const now = new Date();
  const reportDate = options.reportDate ||
    `${String(now.getDate()).padStart(2,'0')}-${String(now.getMonth()+1).padStart(2,'0')}-${now.getFullYear()}`;
  const reportTime = `${String(now.getHours()).padStart(2,'0')}:${String(now.getMinutes()).padStart(2,'0')}`;
  const userName = options.userName || 'User';

  fs.mkdirSync(config.paths.reports, { recursive: true });
  const fileName = `email_report_${reportDate.replace(/-/g, '_')}.pdf`;
  const filePath = path.join(config.paths.reports, fileName);

  logger.info('PDF generation started');

  return new Promise((resolve) => {
    try {
      const doc = new PDFDocument({
        size: 'A4',
        margins: { top: 50, bottom: 50, left: 50, right: 50 },
        info: { Title: 'InboxInsights Email Digest', Author: 'InboxInsights', Subject: 'Email Report - ' + reportDate },
      });
      const stream = fs.createWriteStream(filePath);
      doc.pipe(stream);

      // Header
      doc.rect(0, 0, 595, 100).fill('#042f2e');
      doc.fontSize(26).font('Helvetica-Bold').fillColor('#ffffff')
        .text('INBOXINSIGHTS REPORT', 50, 30, { align: 'center' });
      doc.fontSize(11).font('Helvetica').fillColor('#5eead4')
        .text(sanitizeText(userName) + '  |  ' + reportDate + '  |  Generated at ' + reportTime, 50, 65, { align: 'center' });

      doc.y = 120;

      if (!emails || emails.length === 0) {
        doc.moveDown(3);
        doc.fontSize(14).font('Helvetica').fillColor('#888888')
          .text('No new emails were found for the selected accounts.', { align: 'center' });
        doc.moveDown(2);
      } else {
        const grouped = {};
        for (const email of emails) {
          if (!grouped[email.account]) grouped[email.account] = [];
          grouped[email.account].push(email);
        }
        const accountKeys = Object.keys(grouped).sort();

        for (const account of accountKeys) {
          const accountEmails = grouped[account];
          if (doc.y > 680) doc.addPage();

          // Account header bar
          doc.rect(50, doc.y, 495, 28).fill('#f0fdfa');
          doc.fontSize(11).font('Helvetica-Bold').fillColor('#0f766e')
            .text('Account: ' + sanitizeText(account), 60, doc.y + 8 - 28 + 28, { width: 475 });
          doc.y += 8;

          accountEmails.forEach((email, index) => {
            if (doc.y > 720) doc.addPage();
            doc.fontSize(10).font('Helvetica-Bold').fillColor('#1e293b')
              .text((index + 1) + '. ' + sanitizeText(email.subject), 60, doc.y, { width: 460, indent: 0 });
            doc.fontSize(8).font('Helvetica').fillColor('#64748b')
              .text('From: ' + sanitizeText(email.sender) + '  |  ' + sanitizeText(email.date), 72, doc.y, { width: 448 });
            doc.moveDown(0.3);
          });
          doc.moveDown(0.8);
        }
      }

      // Footer summary
      if (doc.y > 700) doc.addPage();
      doc.moveDown(1);
      const footY = doc.y;
      doc.rect(50, footY, 495, 60).fill('#f0fdfa');
      const uniqueAccounts = emails ? [...new Set(emails.map(e => e.account))].length : 0;
      const totalEmails = emails ? emails.length : 0;
      doc.fontSize(10).font('Helvetica-Bold').fillColor('#042f2e');
      doc.text('Total Gmail Accounts: ' + uniqueAccounts, 60, footY + 10);
      doc.text('Total Emails: ' + totalEmails, 60, footY + 25);
      doc.text('Report Generated At: ' + reportTime, 60, footY + 40);

      doc.moveDown(2);
      doc.fontSize(8).font('Helvetica').fillColor('#aaaaaa')
        .text('This report was automatically generated by InboxInsights.', { align: 'center' });

      doc.end();
      stream.on('finish', () => {
        logger.info('PDF generated successfully: ' + filePath);
        resolve({ success: true, filePath, fileName, error: null });
      });
      stream.on('error', (err) => {
        logger.error('PDF stream error: ' + err.message);
        resolve({ success: false, filePath: null, fileName: null, error: err.message });
      });
    } catch (error) {
      logger.error('PDF generation failed: ' + error.message);
      resolve({ success: false, filePath: null, fileName: null, error: error.message });
    }
  });
}

module.exports = { generateReport };
