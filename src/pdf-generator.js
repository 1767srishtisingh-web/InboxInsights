const PDFDocument = require('pdfkit');
const fs = require('fs');
const path = require('path');
const config = require('./config');
const logger = require('./logger');

/**
 * Generate a PDF report of email subjects.
 * @param {Array} emails - Array of normalized email objects { account, sender, subject, date, message_id }
 * @param {Object} options - Generation options
 * @param {string} options.reportDate - Report date string (DD-MM-YYYY)
 * @returns {Promise<{success: boolean, filePath: string|null, error: string|null}>}
 */
async function generateReport(emails, options = {}) {
  const now = new Date();
  const reportDate = options.reportDate || 
    `${String(now.getDate()).padStart(2, '0')}-${String(now.getMonth() + 1).padStart(2, '0')}-${now.getFullYear()}`;
  const reportTime = `${String(now.getHours()).padStart(2, '0')}:${String(now.getMinutes()).padStart(2, '0')}`;

  // Ensure reports directory exists
  fs.mkdirSync(config.paths.reports, { recursive: true });

  const fileName = `email_report_${reportDate.replace(/-/g, '_')}.pdf`;
  const filePath = path.join(config.paths.reports, fileName);

  logger.info('PDF generation started');

  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({
        size: 'A4',
        margins: { top: 50, bottom: 50, left: 50, right: 50 },
        info: {
          Title: 'Smart Email Report',
          Author: 'InboxInsights',
          Subject: `Email Report - ${reportDate}`,
        },
      });

      const stream = fs.createWriteStream(filePath);
      doc.pipe(stream);

      // --- Header ---
      doc.fontSize(24).font('Helvetica-Bold').fillColor('#1a73e8')
        .text('SMART EMAIL REPORT', { align: 'center' });
      doc.moveDown(0.5);
      
      doc.fontSize(12).font('Helvetica').fillColor('#666666')
        .text(`Date: ${reportDate}`, { align: 'center' });
      doc.moveDown(0.3);
      doc.fontSize(10).fillColor('#999999')
        .text('Generated by InboxInsights', { align: 'center' });
      
      // Divider
      doc.moveDown(1);
      doc.moveTo(50, doc.y).lineTo(545, doc.y).strokeColor('#e0e0e0').lineWidth(1).stroke();
      doc.moveDown(1);

      // --- Handle empty state ---
      if (!emails || emails.length === 0) {
        doc.fontSize(14).font('Helvetica').fillColor('#999999')
          .text('No new emails were found for the selected accounts.', {
            align: 'center',
          });
        doc.moveDown(2);
      } else {
        // Group emails by account
        const grouped = {};
        for (const email of emails) {
          if (!grouped[email.account]) {
            grouped[email.account] = [];
          }
          grouped[email.account].push(email);
        }

        const accountKeys = Object.keys(grouped).sort();

        for (const account of accountKeys) {
          const accountEmails = grouped[account];

          // Check if we need a new page
          if (doc.y > 680) {
            doc.addPage();
          }

          // Account header
          doc.fontSize(13).font('Helvetica-Bold').fillColor('#333333')
            .text(`Account: ${account}`, { underline: false });
          
          // Accent bar under account name
          doc.moveDown(0.3);
          const barY = doc.y;
          doc.moveTo(50, barY).lineTo(250, barY).strokeColor('#1a73e8').lineWidth(2).stroke();
          doc.moveDown(0.5);

          // Email subjects
          accountEmails.forEach((email, index) => {
            // Check for page break
            if (doc.y > 720) {
              doc.addPage();
            }

            doc.fontSize(10).font('Helvetica').fillColor('#333333')
              .text(`${index + 1}. ${email.subject}`, {
                indent: 15,
                width: 460,
              });
            
            // Show sender and date in smaller text
            doc.fontSize(8).fillColor('#888888')
              .text(`From: ${email.sender} | ${email.date}`, {
                indent: 25,
                width: 450,
              });
            doc.moveDown(0.3);
          });

          doc.moveDown(0.8);
        }
      }

      // --- Footer / Summary ---
      // Ensure we have space for the footer
      if (doc.y > 680) {
        doc.addPage();
      }

      doc.moveDown(1);
      doc.moveTo(50, doc.y).lineTo(545, doc.y).strokeColor('#e0e0e0').lineWidth(1).stroke();
      doc.moveDown(0.8);

      // Count unique accounts
      const uniqueAccounts = emails ? [...new Set(emails.map(e => e.account))].length : 0;
      const totalEmails = emails ? emails.length : 0;

      doc.fontSize(10).font('Helvetica-Bold').fillColor('#333333');
      doc.text(`Total Gmail Accounts: ${uniqueAccounts}`);
      doc.text(`Total Emails: ${totalEmails}`);
      doc.text(`Report Generated At: ${reportTime}`);

      doc.moveDown(1);
      doc.fontSize(8).font('Helvetica').fillColor('#aaaaaa')
        .text('This report was automatically generated by InboxInsights.', { align: 'center' });

      doc.end();

      stream.on('finish', () => {
        logger.info(`PDF generated successfully: ${filePath}`);
        resolve({ success: true, filePath, error: null });
      });

      stream.on('error', (err) => {
        logger.error(`PDF stream error: ${err.message}`);
        resolve({ success: false, filePath: null, error: err.message });
      });
    } catch (error) {
      logger.error(`PDF generation failed: ${error.message}`);
      resolve({ success: false, filePath: null, error: error.message });
    }
  });
}

module.exports = {
  generateReport,
};
